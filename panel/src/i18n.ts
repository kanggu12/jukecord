/** The languages. */
export type Lang = 'en' | 'ko';

/** The language in use: the menu's choice, else the browser's. */
export function pickLang(choice: string | null): Lang {
  if (choice === 'en' || choice === 'ko') return choice;
  return navigator.languages.some((tag) => tag.toLowerCase().startsWith('ko')) ? 'ko' : 'en';
}

/** The words of a language. */
export function words(lang: Lang): Strings {
  return lang === 'ko' ? KO : (EN as unknown as Strings);
}

